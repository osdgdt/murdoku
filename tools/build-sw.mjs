// Regenerates what is derived from the files: the PRECACHE list + VERSION hash inside sw.js, and the block of <link
// rel="modulepreload"> in the head of the game pages (player.html, campaign.html: every module the page imports statically,
// so the browser fetches them all at once instead of discovering them level by level while the first ones are being read; at low
// priority, so that the stylesheets, which hold up the first paint, are not made to wait for them).
//   node tools/build-sw.mjs          rewrite them
//   node tools/build-sw.mjs --check  exit 1 if any is stale (used by `npm test`)
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const INCLUDE_DIRS = ["src", "styles", "icons", "examples", "fonts"];

// A Windows checkout may have CRLF line endings: everything derived (the hash included) is computed on LF text, so the result is
// the same on every system, and a file is written back with the line endings it already had.
const toLF = (text) => text.replace(/\r\n/g, "\n");
const withEolOf = (text, like) => (like.includes("\r\n") ? text.replace(/\n/g, "\r\n") : text);
const TEXT_FILE = /\.(html|js|mjs|css|json|svg|webmanifest|md|txt)$/;

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    statSync(full).isDirectory() ? walk(full, out) : out.push(full);
  }
  return out;
}

// ---- modulepreload for the game pages
const PRELOAD_PAGES = ["player.html", "campaign.html"];
const PRELOAD_BLOCK = /[ \t]*<!-- BEGIN PRELOAD[^\n]*-->\n[\s\S]*?[ \t]*<!-- END PRELOAD -->\n/;

// The modules a page loads at once: its <script type="module"> entries and everything they import statically (import ... from,
// export ... from, import "x"). Dynamic import() is not followed: those are loaded later, when they are needed.
export function staticModules(html) {
  const entries = [...html.matchAll(/<script type="module" src="([^"]+)"/g)].map((m) => m[1]);
  const seen = new Set();
  const queue = [...entries];
  while (queue.length) {
    const file = queue.shift();
    if (seen.has(file)) continue;
    let source;
    try {
      source = readFileSync(path.join(root, file), "utf8");
    } catch {
      continue;
    }
    seen.add(file);
    const specifiers = [
      ...source.matchAll(/(?:^|\n)[ \t]*(?:import|export)\s[^;'"]*?from\s*["']([^"']+)["']/g),
      ...source.matchAll(/(?:^|\n)[ \t]*import\s*["']([^"']+)["']/g),
    ].map((m) => m[1]);
    for (const spec of specifiers)
      if (spec.startsWith(".")) queue.push(path.posix.normalize(path.posix.join(path.posix.dirname(file), spec)));
  }
  return { entries, modules: [...seen].filter((f) => !entries.includes(f)).sort() };
}

function preloadedHtml(page) {
  const file = path.join(root, page);
  const raw = readFileSync(file, "utf8");
  const current = toLF(raw);
  const { modules } = staticModules(current);
  const lines = modules.map((f) => `  <link rel="modulepreload" href="${f}" fetchpriority="low" />`).join("\n");
  const block = `  <!-- BEGIN PRELOAD (generated by tools/build-sw.mjs: npm run build:sw) -->\n${lines}\n  <!-- END PRELOAD -->\n`;
  const next = PRELOAD_BLOCK.test(current)
    ? current.replace(PRELOAD_BLOCK, block)
    : current.replace(/( {2}<link rel="stylesheet" href="styles\/contrast\.css" \/>\n)/, `$1${block}`); // after the stylesheets: they come first
  return { file, current: raw, next: withEolOf(next, raw), nextLF: next };
}

function precacheFiles() {
  const keep = (f) => !f.endsWith(".md");
  const files = readdirSync(root)
    .filter((f) => f.endsWith(".html") || f === "manifest.webmanifest")
    .sort();
  for (const dir of INCLUDE_DIRS)
    files.push(
      ...walk(path.join(root, dir))
        .map((f) => path.relative(root, f))
        .filter(keep)
    );
  return files.map((f) => f.split(path.sep).join("/")).filter((f) => f !== "icons/icon.svg");
}

export function generate() {
  const pages = PRELOAD_PAGES.map(preloadedHtml);
  // the files' hash includes the pages as they will be written
  const written = new Map(pages.map((p) => [path.relative(root, p.file), p.nextLF]));
  const files = precacheFiles();
  const hash = createHash("sha256");
  for (const f of files) {
    const body = written.get(f) ?? (TEXT_FILE.test(f) ? toLF(readFileSync(path.join(root, f), "utf8")) : readFileSync(path.join(root, f)));
    hash.update(f).update(body);
  }
  const version = hash.digest("hex").slice(0, 12);
  const block = `const VERSION = ${JSON.stringify(version)};\nconst PRECACHE = ${JSON.stringify(["./", ...files], null, 2)};`;
  const swPath = path.join(root, "sw.js");
  const current = readFileSync(swPath, "utf8");
  const nextLF = toLF(current).replace(
    /\/\/ BEGIN GENERATED\n[\s\S]*?\n\/\/ END GENERATED/,
    `// BEGIN GENERATED\n${block}\n// END GENERATED`
  );
  const next = withEolOf(nextLF, current);
  return { swPath, current, next, pages };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { swPath, current, next, pages } = generate();
  const stale = [...(current !== next ? ["sw.js"] : []), ...pages.filter((p) => p.current !== p.next).map((p) => path.basename(p.file))];
  if (process.argv.includes("--check")) {
    if (stale.length > 0) {
      console.error(`${stale.join(", ")} obsolet${stale.length > 1 ? "i" : "o"}: esegui \`npm run build:sw\` e committa il risultato.`);
      process.exit(1);
    }
    console.log("sw.js e il precaricamento dei moduli sono aggiornati.");
  } else {
    for (const p of pages) writeFileSync(p.file, p.next);
    writeFileSync(swPath, next);
    console.log("sw.js e il precaricamento dei moduli rigenerati.");
  }
}
